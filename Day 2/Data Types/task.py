# string (has quotations)
print("123" + "345")

# integer = whole number
print(123 + 345)

# large integers
print(123_456_789)

# float = floating point number (decimal point can "float" anywhere around the number)
print(3.14159)

# boolean (2 possible values: true or false)
print(True)
print(False)
